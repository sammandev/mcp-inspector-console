import { readFile } from 'node:fs/promises'
import { join } from 'node:path'

import type { ParityItem } from '../../feature-parity/src/catalog.ts'
import type { UpstreamRecord } from './types.ts'
import { validateManifest } from './validate.ts'

const MCP_USE_COMMIT = '8ff4b865e0e5712c66d5077e93392807daca9354'
const OFFICIAL_COMMIT = 'eb54b447e5377a7a18acaea9602fced5cb4c5b9f'

const escapeCell = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ')

function validateInventories(parity: readonly ParityItem[], manifest: readonly UpstreamRecord[]) {
  const manifestErrors = validateManifest(manifest)
  if (manifestErrors.length) {
    throw new Error(`Invalid upstream manifest: ${manifestErrors.map(({ index, field, message }) => `record ${index} ${field}: ${message}`).join('; ')}`)
  }

  const features = new Set(parity.map(({ feature }) => feature))
  if (features.size !== parity.length) throw new Error('Feature parity catalog contains duplicate features')
  if (!parity.every(({ status, ownerPhase, source, note }) => status && ownerPhase && source && note)) {
    throw new Error('Every feature requires one status, owner phase, source, and note')
  }

  const mcpUse = manifest.find(({ upstream }) => upstream === 'mcp-use')
  const official = manifest.find(({ upstream }) => upstream === 'official-inspector')
  if (mcpUse?.commit !== MCP_USE_COMMIT || mcpUse.classification !== 'dependency-only') {
    throw new Error(`mcp-use must be pinned as dependency-only at ${MCP_USE_COMMIT}`)
  }
  if (official?.commit !== OFFICIAL_COMMIT || official.classification !== 'reference-only') {
    throw new Error(`Official Inspector must be pinned as reference-only at ${OFFICIAL_COMMIT}`)
  }

  const copiedOfficial = manifest.filter(({ upstream, classification }) =>
    upstream === 'official-inspector' && (classification === 'copied-file' || classification === 'copied-documentation'))
  if (copiedOfficial.length) throw new Error('Phase 0 permits zero copied Official Inspector files')
  const blockedRuntime = parity.filter(({ source, ownerPhase }) => source === 'official-inspector' && ownerPhase !== 'phase-0')
  if (blockedRuntime.some(({ status }) => status !== 'blocked-license')) {
    throw new Error('Future Official runtime features must remain blocked-license')
  }
}

export function generateReports(parity: readonly ParityItem[], manifest: readonly UpstreamRecord[]) {
  validateInventories(parity, manifest)
  const copiedOfficialCount = manifest.filter(({ upstream, classification }) =>
    upstream === 'official-inspector' && (classification === 'copied-file' || classification === 'copied-documentation')).length

  const parityRows = parity.map((item) => `| ${escapeCell(item.feature)} | ${item.status} | ${item.ownerPhase} | ${item.source} | ${escapeCell(item.note)} |`)
  const parityReport = [
    '# Feature parity',
    '',
    '<!-- Generated by `pnpm verify:provenance`; do not edit directly. -->',
    '',
    `Reference revisions: mcp-use \`${MCP_USE_COMMIT}\`; Official Inspector \`${OFFICIAL_COMMIT}\`.`,
    '',
    'Each combined feature has exactly one status, owner phase, and upstream origin/source.',
    '',
    '| Feature | Status | Owner phase | Source | Note |',
    '| --- | --- | --- | --- | --- |',
    ...parityRows,
    '',
    '## Status meanings',
    '',
    '- `implemented`: present in Phase 0.',
    '- `phase-placeholder`: represented in the scaffold and owned by a later phase.',
    '- `rebuild`: intentionally recreated around published contracts or a combined design.',
    '- `non-applicable`: intentionally not part of the combined product.',
    '- `blocked-license`: future Official runtime reuse is pending positive file-level legal approval.',
    '',
  ].join('\n')

  const provenanceRows = manifest.map((record) => {
    const location = record.classification === 'dependency-only'
      ? (record.packageNames ?? []).join(', ')
      : record.sourcePath ?? '—'
    return `| ${record.upstream} | \`${record.commit}\` | ${record.classification} | ${escapeCell(location)} | ${record.localPath ?? '—'} | ${record.license} | ${escapeCell(record.attribution)} | ${escapeCell(record.note)} |`
  })
  const provenanceReport = [
    '# Upstream provenance',
    '',
    '<!-- Generated by `pnpm verify:provenance`; do not edit directly. -->',
    '',
    `Official copied files: **${copiedOfficialCount}**`,
    '',
    'Phase 0 copies no Official Inspector files. Dependency-only mcp-use records identify package names rather than invented copied source paths. Future Official runtime code remains `blocked-license` until positive human/legal file-level classification.',
    '',
    '| Upstream | Pinned commit | Classification | Source/package | Local path | License | Attribution | Note |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...provenanceRows,
    '',
  ].join('\n')

  return { parity: parityReport, provenance: provenanceReport }
}

export async function verifyReports(root: string, parity: readonly ParityItem[], manifest: readonly UpstreamRecord[]) {
  const expected = generateReports(parity, manifest)
  const reports = [
    ['feature-parity.md', expected.parity],
    ['upstream-provenance.md', expected.provenance],
  ] as const

  for (const [name, content] of reports) {
    const actual = await readFile(join(root, name), 'utf8')
    if (actual !== content) throw new Error(`${name} has drifted from the typed catalogs; run the provenance verifier generator`)
  }
}
